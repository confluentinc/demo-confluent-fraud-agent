"""
Write terraform/terraform.tfvars from credentials.env values.

The demo takes only the Confluent Cloud key/secret and the AWS Bedrock key/secret
(plus a session token for temporary AWS credentials) and the workshop-mode flag;
region, model, names, and sizing are fixed in terraform/main.tf locals.
"""

import shutil
from pathlib import Path

from .terraform import terraform_dir


def get_credential_value(creds: dict[str, str], key: str) -> str | None:
    """Get a credential, checking both bare and TF_VAR_-prefixed keys."""
    return creds.get(key) or creds.get(f"TF_VAR_{key}")


def write_tfvars_file(tfvars_path: Path, content: str) -> bool:
    """Write tfvars, keeping a .backup of the previous file."""
    try:
        if tfvars_path.exists():
            shutil.copy2(tfvars_path, tfvars_path.with_suffix(".tfvars.backup"))
        tfvars_path.parent.mkdir(parents=True, exist_ok=True)
        tfvars_path.write_text(content)
        tfvars_path.chmod(0o600)
        return True
    except Exception as e:
        print(f"Error writing {tfvars_path}: {e}")
        return False


def generate_tfvars_content(
    confluent_cloud_api_key: str,
    confluent_cloud_api_secret: str,
    aws_bedrock_access_key: str,
    aws_bedrock_secret_key: str,
    aws_session_token: str | None = None,
    deploy_flink_pipeline: bool = True,
) -> str:
    content = f"""# Generated by `uv run deploy` from credentials.env — edit credentials.env, not this file.
confluent_cloud_api_key    = "{confluent_cloud_api_key}"
confluent_cloud_api_secret = "{confluent_cloud_api_secret}"
aws_bedrock_access_key     = "{aws_bedrock_access_key}"
aws_bedrock_secret_key     = "{aws_bedrock_secret_key}"
"""
    if aws_session_token:
        content += f'aws_session_token          = "{aws_session_token}"\n'
    content += f"deploy_flink_pipeline      = {'true' if deploy_flink_pipeline else 'false'}\n"
    return content


def is_workshop_mode(creds: dict[str, str]) -> bool:
    return (get_credential_value(creds, "deploy_flink_pipeline") or "true").strip().lower() == "false"


def write_tfvars_for_deployment(root: Path, creds: dict[str, str]) -> bool:
    """Write terraform/terraform.tfvars; returns False when required values are missing."""
    values = {
        key: get_credential_value(creds, key)
        for key in (
            "confluent_cloud_api_key",
            "confluent_cloud_api_secret",
            "aws_bedrock_access_key",
            "aws_bedrock_secret_key",
        )
    }
    if not all(values.values()):
        return False
    tfvars_path = terraform_dir(root) / "terraform.tfvars"
    content = generate_tfvars_content(
        **values,
        aws_session_token=get_credential_value(creds, "aws_session_token"),
        deploy_flink_pipeline=not is_workshop_mode(creds),
    )
    if write_tfvars_file(tfvars_path, content):
        print(f"✓ Wrote {tfvars_path}")
        return True
    return False
