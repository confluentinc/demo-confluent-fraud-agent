"""
Write terraform/terraform.tfvars from credentials.env values.

The demo takes only the Confluent Cloud key/secret, the LLM provider, the AWS
Bedrock key/secret when that provider is "bedrock" (plus a session token for
temporary AWS credentials), and the workshop-mode flag; region, model, names, and
sizing are fixed in terraform/main.tf locals.
"""

import json
import shutil
from pathlib import Path

from .terraform import terraform_dir

# What backs fraud_model (`llm_provider` in terraform/variables.tf). "confluent" is
# CSP Hosted Flink Model Inference: no AWS keys at all, and the default;
# `uv run deploy --bedrock` opts into Bedrock. Saved in credentials.env.
LLM_PROVIDER_KEY = "TF_VAR_llm_provider"
LLM_PROVIDERS = {
    "confluent": "CSP Hosted Flink Model Inference (Confluent-hosted, no AWS keys)",
    "bedrock": "AWS Bedrock (your own AWS access keys)",
}
DEFAULT_LLM_PROVIDER = "confluent"


def get_credential_value(creds: dict[str, str], key: str) -> str | None:
    """Get a credential, checking both bare and TF_VAR_-prefixed keys."""
    return creds.get(key) or creds.get(f"TF_VAR_{key}")


def write_tfvars_file(tfvars_path: Path, content: str) -> bool:
    """Write tfvars, keeping a .backup of the previous file."""
    try:
        if tfvars_path.exists():
            shutil.copy2(tfvars_path, tfvars_path.with_suffix(".tfvars.backup"))
        tfvars_path.parent.mkdir(parents=True, exist_ok=True)
        tfvars_path.write_text(content)
        tfvars_path.chmod(0o600)
        return True
    except Exception as e:
        print(f"Error writing {tfvars_path}: {e}")
        return False


def generate_tfvars_content(
    confluent_cloud_api_key: str,
    confluent_cloud_api_secret: str,
    aws_bedrock_access_key: str = "",
    aws_bedrock_secret_key: str = "",
    aws_session_token: str | None = None,
    deploy_flink_pipeline: bool = True,
    llm_provider: str = DEFAULT_LLM_PROVIDER,
) -> str:
    content = f"""# Generated by `uv run deploy` from credentials.env — edit credentials.env, not this file.
confluent_cloud_api_key    = "{confluent_cloud_api_key}"
confluent_cloud_api_secret = "{confluent_cloud_api_secret}"
llm_provider               = "{llm_provider}"
"""
    if llm_provider == "bedrock":
        content += f'aws_bedrock_access_key     = "{aws_bedrock_access_key}"\n'
        content += f'aws_bedrock_secret_key     = "{aws_bedrock_secret_key}"\n'
    if llm_provider == "bedrock" and aws_session_token:
        content += f'aws_session_token          = "{aws_session_token}"\n'
    content += f"deploy_flink_pipeline      = {'true' if deploy_flink_pipeline else 'false'}\n"
    return content


def is_workshop_mode(creds: dict[str, str]) -> bool:
    return (get_credential_value(creds, "deploy_flink_pipeline") or "true").strip().lower() == "false"


def saved_llm_provider(creds: dict[str, str]) -> str:
    """credentials.env's provider, else the default. Raises ValueError on an unknown value."""
    value = (creds.get(LLM_PROVIDER_KEY) or DEFAULT_LLM_PROVIDER).strip()
    if value not in LLM_PROVIDERS:
        raise ValueError(f"{LLM_PROVIDER_KEY}={value!r} — expected one of: {', '.join(LLM_PROVIDERS)}")
    return value


def deployed_llm_provider(root: Path) -> str | None:
    """What the live fraud_model is backed by, read from Terraform state.

    Only Bedrock creates `confluent_flink_connection.bedrock`. None when nothing is
    deployed or the state can't be read. Workshop mode never creates the model, so
    there the connection alone decides.
    """
    try:
        resources = json.loads((terraform_dir(root) / "terraform.tfstate").read_text()).get("resources", [])
    except (OSError, ValueError):
        return None
    live = {r.get("name") for r in resources if r.get("instances")}
    if not live:
        return None
    return "bedrock" if "bedrock" in live else "confluent"


# The terraform/flink.tf modules gated on deploy_flink_pipeline (demo mode only).
DEMO_PIPELINE_MODULES = ("model", "tool_flag", "tool_freeze", "tool_notify", "agent", "profiles", "detect")


def deployed_demo_pipeline(root: Path) -> bool:
    """Whether Terraform state holds the demo-mode AI pipeline statements.

    Destroying those statements (by switching to workshop mode) does not drop the
    model, tools, agent, or activity_profiles they created, so the attendee's own
    CREATE statements would then fail with "already exists".
    """
    try:
        resources = json.loads((terraform_dir(root) / "terraform.tfstate").read_text()).get("resources", [])
    except (OSError, ValueError):
        return False
    demo = {f"module.{name}[0]" for name in DEMO_PIPELINE_MODULES}
    return any(r.get("module", "").split(".module.")[0] in demo and r.get("instances") for r in resources)


def llm_provider_for(root: Path, creds: dict[str, str], requested: str | None = None) -> str:
    """The provider to deploy: requested (--bedrock / an exported TF_VAR_llm_provider),
    else what is deployed now, else credentials.env.

    The deployed state wins over credentials.env so a deployment made before the
    provider was saved (always Bedrock) is never silently swapped onto CSP, which
    would re-run CREATE MODEL against an existing name.
    """
    saved = saved_llm_provider(creds)
    deployed = deployed_llm_provider(root)
    if requested:
        requested = saved_llm_provider({LLM_PROVIDER_KEY: requested})
        if deployed and deployed != requested:
            print(f"  ⚠ Switching the LLM provider from {deployed!r} to {requested!r} on a live deployment")
            print("    re-runs CREATE MODEL against an existing name and fails — `uv run destroy` first.")
        return requested
    if deployed and deployed != saved:
        print(f"  LLM provider: keeping {deployed!r}, which this deployment runs now")
        print(f"    (credentials.env says {saved!r}; `uv run destroy` first to switch it).")
    return deployed or saved


def write_tfvars_for_deployment(root: Path, creds: dict[str, str]) -> bool:
    """Write terraform/terraform.tfvars; returns False when required values are missing."""
    llm_provider = saved_llm_provider(creds)
    required = ["confluent_cloud_api_key", "confluent_cloud_api_secret"]
    if llm_provider == "bedrock":
        required += ["aws_bedrock_access_key", "aws_bedrock_secret_key"]
    values = {key: get_credential_value(creds, key) for key in required}
    if not all(values.values()):
        return False
    tfvars_path = terraform_dir(root) / "terraform.tfvars"
    content = generate_tfvars_content(
        **values,
        aws_session_token=get_credential_value(creds, "aws_session_token"),
        deploy_flink_pipeline=not is_workshop_mode(creds),
        llm_provider=llm_provider,
    )
    if write_tfvars_file(tfvars_path, content):
        print(f"✓ Wrote {tfvars_path}")
        return True
    return False
